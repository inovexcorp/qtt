/** One query parameter of the test request. */
export interface TestParam {
  key: string;
  value: string;
}

/** A variable the template reads, as the server found it. */
interface TemplateVariable {
  name: string;
  defaultValue?: string | null;
}

/** What a test run answered. */
export interface TestOutcome {
  ok: boolean;
  sparql: string;
  results: unknown;
  error: string;
  stackTrace: string;
  timeMs: number | null;
}

/** {name: {first: "Ada"}} under "body" → {"body.name.first": "Ada"} (arrays and values as strings). */
export function flattenJson(value: unknown, prefix: string): Record<string, string> {
  const out: Record<string, string> = {};
  if (value && typeof value === 'object' && !Array.isArray(value)) {
    for (const [key, v] of Object.entries(value as Record<string, unknown>)) {
      const name = prefix ? `${prefix}.${key}` : key;
      if (v && typeof v === 'object' && !Array.isArray(v)) {
        Object.assign(out, flattenJson(v, name));
      } else {
        out[name] = String(v);
      }
    }
  }
  return out;
}

/** SPARQL JSON results as a table (null when they aren't SELECT results). */
export function resultTable(results: unknown, limit = 200): { vars: string[]; rows: string[][]; total: number } | null {
  const r = results as { head?: { vars?: string[] }; results?: { bindings?: Record<string, { value?: string }>[] } } | null;
  const vars = r?.head?.vars;
  const bindings = r?.results?.bindings;
  if (!Array.isArray(vars) || !Array.isArray(bindings)) {
    return null;
  }
  return {
    vars,
    rows: bindings.slice(0, limit).map(b => vars.map(v => b?.[v]?.value ?? '')),
    total: bindings.length,
  };
}

const JSON_EDITOR_OPTIONS: monaco.editor.IStandaloneEditorConstructionOptions = {
  theme: 'vs-dark', language: 'json', automaticLayout: true, minimap: { enabled: false }, fontSize: 13,
  lineNumbers: 'off', scrollBeyondLastLine: false, padding: { top: 8, bottom: 8 },
};

/**
 * Trying a route out: a request built from the variables its template reads (a JSON body and query parameters),
 * optionally generated by SPARQi, run against the datasource with the route as it is being edited (saved or not),
 * and what came back: the SPARQL it built, the results, or the error.
 *
 * Results stay when switching tabs. Reading the template's variables again is offered when the template changed.
 */
@Component({
  selector: 'qtt-route-test',
  templateUrl: './route-test.component.html',
  styleUrl: './route-test.component.scss',
  changeDetection: ChangeDetectionStrategy.OnPush,
  imports: [FormsModule, JsonPipe, MatButton, MatIconButton, MatIcon, MatFormField, MatLabel, MatInput, MatCheckbox,
    MatTooltip, MatProgressSpinner, MatButtonToggleGroup, MatButtonToggle, CodeEditorComponent],
})
export class RouteTestComponent {
  protected readonly draft = inject(RouteDraft);
  private readonly api = inject(ConfigRouteService);
  private readonly sparqi = inject(SparqiService);

  readonly routeId = input('');
  readonly sparqiEnabled = input(false);
  /** Running a test needs the editor role (it runs a query on the datasource). */
  readonly canRun = input(true);

  protected readonly jsonOptions = JSON_EDITOR_OPTIONS;

  // Request
  protected readonly loadingVariables = signal(false);
  protected readonly variablesError = signal<string | null>(null);
  /** The template the variables were read from (null: not read yet). */
  private readonly readFrom = signal<string | null>(null);
  protected readonly detectedBody = signal(false);
  protected body = '{}';
  protected readonly params = signal<TestParam[]>([]);

  // SPARQi
  protected sparqiContext = '';
  protected edgeCases = false;
  protected readonly generating = signal(false);
  protected readonly generated = signal<{ reasoning: string; confidence: number; queries: number } | null>(null);
  protected readonly generateError = signal<string | null>(null);

  // Result
  protected readonly running = signal(false);
  protected readonly outcome = signal<TestOutcome | null>(null);
  protected readonly view = signal<'table' | 'json'>('table');
  protected readonly table = computed(() => resultTable(this.outcome()?.results));

  /** The template changed since its variables were read. */
  protected readonly stale = computed(() => {
    const from = this.readFrom();
    return from !== null && from !== this.draft.snapshot().template;
  });

  /** Reads the template's variables the first time the tab is shown (or again on request). */
  ensureLoaded(): void {
    if (this.readFrom() === null && !this.loadingVariables()) {
      void this.readVariables();
    }
  }

  async readVariables(): Promise<void> {
    const template = this.draft.snapshot().template;
    this.loadingVariables.set(true);
    this.variablesError.set(null);
    try {
      const response = await firstValueFrom(this.api.extractTestVariables(template)) as
        { variables?: TemplateVariable[]; sampleBodyJson?: string | null };
      const variables = response.variables ?? [];
      // Keep values already typed for parameters that are still there
      const typed = new Map(this.params().map(p => [p.key, p.value]));
      this.params.set(variables.filter(v => v.name.startsWith('headers.')).map(v => {
        const key = v.name.substring('headers.'.length);
        return { key, value: typed.get(key) ?? v.defaultValue ?? '' };
      }));
      this.detectedBody.set(!!response.sampleBodyJson);
      if (this.readFrom() === null || this.body.trim() === '{}' || !this.body.trim()) {
        this.body = response.sampleBodyJson || '{}';
      }
      this.readFrom.set(template);
    } catch (error) {
      this.variablesError.set(saveErrorMessage(error));
      this.readFrom.set(template);
    } finally {
      this.loadingVariables.set(false);
    }
  }

  protected addParam(): void {
    this.params.update(list => [...list, { key: '', value: '' }]);
  }

  protected removeParam(index: number): void {
    this.params.update(list => list.filter((_, i) => i !== index));
  }

  protected setParam(index: number, change: Partial<TestParam>): void {
    this.params.update(list => list.map((p, i) => i === index ? { ...p, ...change } : p));
  }

  /** Runs the test (reading the variables first if they haven't been). */
  async run(): Promise<void> {
    if (this.running()) {
      return;
    }
    if (this.readFrom() === null) {
      await this.readVariables();
    }
    let body: unknown;
    try {
      body = JSON.parse(this.body || '{}');
    } catch (e) {
      this.outcome.set({ ok: false, sparql: '', results: null, timeMs: null, stackTrace: '',
        error: `The request body isn't valid JSON: ${(e as Error).message}` });
      return;
    }
    const parameters: Record<string, string> = flattenJson(body, 'body');
    for (const p of this.params()) {
      if (p.key.trim() && p.value !== '') {
        parameters[p.key.trim()] = p.value;
      }
    }
    const s = this.draft.snapshot();
    const request = {
      templateContent: s.template,
      dataSourceId: s.datasourceId,
      graphMartUri: s.graphmart,
      // Layer IRIs, as the route itself uses them (titles used to be sent here)
      layers: s.layers.join(','),
      routeParams: 'httpMethodRestrict=' + s.methods.join(','),
      parameters,
    };
    this.running.set(true);
    try {
      const r = await firstValueFrom(this.api.executeRouteTest(request)) as Record<string, unknown>;
      this.outcome.set(r['status'] === 'success'
        ? { ok: true, sparql: String(r['generatedSparql'] ?? ''), results: r['results'], error: '', stackTrace: '',
          timeMs: typeof r['executionTimeMs'] === 'number' ? r['executionTimeMs'] as number : null }
        : { ok: false, sparql: String(r['generatedSparql'] ?? ''), results: null, timeMs: null,
          error: String(r['error'] ?? 'The test failed'), stackTrace: String(r['stackTrace'] ?? '') });
    } catch (error) {
      const body = (error as { error?: Record<string, unknown> }).error;
      this.outcome.set({ ok: false, results: null, timeMs: null,
        sparql: typeof body === 'object' && body ? String(body['generatedSparql'] ?? '') : '',
        stackTrace: typeof body === 'object' && body ? String(body['stackTrace'] ?? '') : '',
        error: typeof body === 'object' && body?.['error'] ? String(body['error']) : saveErrorMessage(error) });
    } finally {
      this.running.set(false);
    }
  }

  /** Has SPARQi fill in the body and parameters from the template, ontology and data. */
  protected async generate(): Promise<void> {
    const s = this.draft.snapshot();
    this.generating.set(true);
    this.generated.set(null);
    this.generateError.set(null);
    try {
      const r = await firstValueFrom(this.sparqi.generateTestRequest({
        routeId: this.routeId(), templateContent: s.template, dataSourceId: s.datasourceId, graphMartUri: s.graphmart,
        layerUris: s.layers, includeEdgeCases: this.edgeCases, userContext: this.sparqiContext.trim() || null,
      }));
      if (r?.bodyJson) {
        this.body = JSON.stringify(r.bodyJson, null, 2);
      }
      if (r?.queryParams) {
        this.params.set(Object.entries(r.queryParams as Record<string, unknown>).map(([key, value]) => ({ key, value: String(value) })));
      }
      const queries = Number(/(\d+)/.exec(r?.toolCallsSummary?.[0] ?? '')?.[1] ?? 0);
      this.generated.set({ reasoning: r?.reasoning || 'Generated test values', confidence: r?.confidence ?? 0.85, queries });
    } catch (error) {
      this.generateError.set(saveErrorMessage(error));
    } finally {
      this.generating.set(false);
    }
  }

  protected percent(n: number): string {
    return `${Math.round(n * 100)}%`;
  }
}
